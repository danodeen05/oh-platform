#!/usr/bin/env node
/**
 * Writes src/generated/test-manifest.ts: the test files, their case counts,
 * pass/fail totals and coverage, plus a hash of the test sources so the
 * committed manifest can be checked for freshness by manifest.test.ts.
 *
 * Run it last, after every other change:  pnpm --filter @oh/plan-model test:manifest
 *
 * The hash is written before vitest runs (so the freshness test sees the
 * current sources) and the totals are filled in after.
 */
import { execSync } from "node:child_process";
import { mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const testsDir = join(root, "src", "__tests__");
const outDir = join(root, "src", "generated");
const outFile = join(outDir, "test-manifest.ts");
const tmpDir = join(root, "node_modules", ".cache", "plan-model-manifest");
const jsonFile = join(tmpDir, "results.json");
const coverageDir = join(tmpDir, "coverage");

/** FNV-1a 32-bit over the concatenated, name-sorted test sources. Mirrored in manifest.test.ts. */
export function hashSources(files) {
  let h = 0x811c9dc5;
  for (const { name, text } of files) {
    for (const ch of `${name}\n${text}\n`) {
      h ^= ch.codePointAt(0);
      h = Math.imul(h, 0x01000193) >>> 0;
    }
  }
  return h.toString(16).padStart(8, "0");
}

function readVersion() {
  const src = readFileSync(join(root, "src", "version.ts"), "utf8");
  const m = /MODEL_VERSION = "([^"]+)"/.exec(src);
  if (!m) throw new Error("MODEL_VERSION not found in src/version.ts");
  return m[1];
}

function listTests() {
  return readdirSync(testsDir)
    .filter((f) => f.endsWith(".test.ts"))
    .sort()
    .map((name) => ({ name, text: readFileSync(join(testsDir, name), "utf8") }));
}

function render({ version, sourcesHash, generatedAt, files, totals, coverage }) {
  const rows = files.map((f) => `  { file: ${JSON.stringify(f.file)}, tests: ${f.tests}, passed: ${f.passed} },`).join("\n");
  return `/* eslint-disable */
// GENERATED by scripts/test-manifest.mjs. Do not edit. Regenerate with: pnpm --filter @oh/plan-model test:manifest
export interface TestManifestFile {
  file: string;
  tests: number;
  passed: number;
}

export interface TestManifest {
  /** MODEL_VERSION at generation time. */
  version: string;
  /** FNV-1a hash of the test sources; manifest.test.ts recomputes it. */
  sourcesHash: string;
  /** ISO timestamp. */
  generatedAt: string;
  files: readonly TestManifestFile[];
  totalTests: number;
  passed: number;
  failed: number;
  coverage: { lines: number; functions: number; branches: number; statements: number };
}

export const TEST_MANIFEST: TestManifest = {
  version: ${JSON.stringify(version)},
  sourcesHash: ${JSON.stringify(sourcesHash)},
  generatedAt: ${JSON.stringify(generatedAt)},
  files: [
${rows}
  ],
  totalTests: ${totals.tests},
  passed: ${totals.passed},
  failed: ${totals.failed},
  coverage: { lines: ${coverage.lines}, functions: ${coverage.functions}, branches: ${coverage.branches}, statements: ${coverage.statements} },
};
`;
}

const version = readVersion();
const sources = listTests();
const sourcesHash = hashSources(sources);
const generatedAt = new Date().toISOString();
mkdirSync(outDir, { recursive: true });
rmSync(tmpDir, { recursive: true, force: true });
mkdirSync(tmpDir, { recursive: true });

// Pass 1: the hash and version, with empty totals, so the freshness test can pass during the run.
const placeholder = { version, sourcesHash, generatedAt, files: sources.map((s) => ({ file: s.name, tests: 0, passed: 0 })), totals: { tests: 0, passed: 0, failed: 0 }, coverage: { lines: 0, functions: 0, branches: 0, statements: 0 } };
writeFileSync(outFile, render(placeholder));

// Pass 2: run the suite with coverage and the JSON reporter.
let exitCode = 0;
try {
  execSync(
    `npx vitest run --coverage --reporter=default --reporter=json --outputFile=${JSON.stringify(jsonFile)} --coverage.reporter=text-summary --coverage.reporter=json-summary --coverage.reportsDirectory=${JSON.stringify(coverageDir)}`,
    { cwd: root, stdio: "inherit" },
  );
} catch (err) {
  exitCode = typeof err?.status === "number" ? err.status : 1;
}

const results = JSON.parse(readFileSync(jsonFile, "utf8"));
const summary = JSON.parse(readFileSync(join(coverageDir, "coverage-summary.json"), "utf8")).total;
const files = results.testResults
  .map((r) => ({ file: r.name.slice(r.name.lastIndexOf("/") + 1), tests: r.assertionResults.length, passed: r.assertionResults.filter((a) => a.status === "passed").length }))
  .sort((a, b) => a.file.localeCompare(b.file));
const totals = { tests: results.numTotalTests, passed: results.numPassedTests, failed: results.numFailedTests };
const coverage = { lines: summary.lines.pct, functions: summary.functions.pct, branches: summary.branches.pct, statements: summary.statements.pct };
writeFileSync(outFile, render({ version, sourcesHash, generatedAt, files, totals, coverage }));
console.log(`wrote ${outFile}: ${totals.tests} tests, ${totals.failed} failed, coverage ${coverage.lines}% lines / ${coverage.branches}% branches`);
process.exit(exitCode);
