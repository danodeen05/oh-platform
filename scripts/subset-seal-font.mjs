#!/usr/bin/env node
/**
 * Builds the chop-seal glyph font (Task G2a): a subset of Noto Serif TC
 * Regular (SIL Open Font License 1.1) holding only the glyphs in
 * components/site/seal/seals.ts, about 5 KB as WOFF2.
 *
 * Why: the rewards and member pages show seals in every locale, and the seal
 * used to name 'Noto Serif TC', which pulled a full CJK web font (hundreds of
 * KB of CSS and font slices) into English pages for 18 characters. Same face,
 * so the seals look exactly as before.
 *
 * Google Fonts builds the subset (`text=`); a Chrome user agent gets WOFF2.
 *
 *   node scripts/subset-seal-font.mjs
 *
 * Writes apps/web/public/fonts/seal-glyphs.woff2 and
 * apps/web/components/site/seal/seal-font.ts (the glyph list the file holds,
 * which a unit test checks against seals.ts). Re-run it when a seal glyph is
 * added.
 */
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const WEB = path.resolve(HERE, "../apps/web");
const SEAL_DIR = path.join(WEB, "components/site/seal");
const UA = "Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0 Safari/537.36";

const src = readFileSync(path.join(SEAL_DIR, "seals.ts"), "utf8");
const glyphs = [...new Set([...src.matchAll(/glyph:\s*"([^"]+)"/g)].map((m) => m[1]))].join("");
if (!glyphs) throw new Error("no glyphs found in seals.ts");

const css = await (
  await fetch(`https://fonts.googleapis.com/css2?family=Noto+Serif+TC:wght@400&text=${encodeURIComponent(glyphs)}`, {
    headers: { "user-agent": UA },
  })
).text();
const url = css.match(/url\(([^)]+)\)/)?.[1];
if (!url) throw new Error(`no font url in:\n${css}`);
const font = Buffer.from(await (await fetch(url, { headers: { "user-agent": UA } })).arrayBuffer());
if (font.subarray(0, 4).toString("latin1") !== "wOF2") throw new Error("expected a WOFF2 file");

mkdirSync(path.join(WEB, "public/fonts"), { recursive: true });
writeFileSync(path.join(WEB, "public/fonts/seal-glyphs.woff2"), font);
writeFileSync(
  path.join(SEAL_DIR, "seal-font.ts"),
  `/**
 * GENERATED by scripts/subset-seal-font.mjs (Task G2a). Do not edit by hand.
 *
 * public/fonts/seal-glyphs.woff2 is Noto Serif TC Regular (SIL Open Font
 * License 1.1) subset to exactly these characters. The @font-face is in
 * app/globals.css ("Oh Seal Glyphs"). Re-run the script after adding a glyph
 * to seals.ts; seal.test.tsx fails until you do.
 */
export const SEAL_FONT_FAMILY = "Oh Seal Glyphs";
export const SEAL_FONT_GLYPHS = "${glyphs}";
`,
);
console.log(`wrote ${font.length} bytes for ${[...glyphs].length} glyphs: ${glyphs}`);
