#!/usr/bin/env node
// Traces the owner's actual tier art (apps/web/public/tiers/*.png) into SVG
// path data with potrace, and writes the result to
// apps/web/components/site/tiers/tier-paths.ts. Task C2, Fix round 1: the
// tier marks were previously hand-redrawn as stroked line art; the owner's
// binding rule is that the marks must be the owner's actual art, traced --
// so this replaces that approximation with a faithful vector trace.
//
// Run: node scripts/trace-tier-marks.mjs
// Re-run whenever the source PNGs change. apps/web/lib/site/__tests__/
// tier-paths.test.ts pins each PNG's sha256 against the header comment
// this script writes, so a changed PNG with a stale trace fails loudly
// instead of drifting silently.

import { Potrace } from "potrace";
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(__dirname, "..");
const tiersDir = path.join(repoRoot, "apps/web/public/tiers");
const outFile = path.join(repoRoot, "apps/web/components/site/tiers/tier-paths.ts");

const TIERS = ["chopstick", "noodle-master", "beef-boss"];

// Tuned against the actual marks (see the "before/after" preview this
// script's author rendered): turdSize low enough to keep individual noodle
// strands and the fine horn tips rather than merging them into blobs,
// optCurve on so the tapered chopstick tips stay smooth curves rather than
// jagged polylines, alphaMax at the library default (sharp corners where
// the art has them, e.g. the bowl rim).
const PARAMS = { threshold: 128, turdSize: 2, optCurve: true, alphaMax: 1, optTolerance: 0.2 };

function sha256(filePath) {
  return createHash("sha256").update(readFileSync(filePath)).digest("hex");
}

function trace(tier) {
  return new Promise((resolve, reject) => {
    const file = path.join(tiersDir, `${tier}.png`);
    const tracer = new Potrace();
    tracer.setParameters(PARAMS);
    tracer.loadImage(file, function (err) {
      if (err) return reject(err);
      const svg = this.getSVG();
      const widthMatch = svg.match(/width="(\d+(?:\.\d+)?)"/);
      const heightMatch = svg.match(/height="(\d+(?:\.\d+)?)"/);
      const dMatch = this.getPathTag().match(/\sd="([^"]+)"/);
      if (!widthMatch || !heightMatch || !dMatch) {
        reject(new Error(`trace-tier-marks: could not parse traced SVG for "${tier}"`));
        return;
      }
      resolve({
        tier,
        viewBox: `0 0 ${widthMatch[1]} ${heightMatch[1]}`,
        d: dMatch[1],
        sha256: sha256(file),
      });
    });
  });
}

const results = await Promise.all(TIERS.map(trace));

const fileHeader = `/**
 * Traced path data for the membership tier marks (Task C2, Fix round 1).
 * GENERATED by scripts/trace-tier-marks.mjs from the owner's actual art in
 * apps/web/public/tiers/*.png. Do not hand-edit; re-run the script if the
 * source PNGs change.
 *
 * Potrace parameters used: ${JSON.stringify(PARAMS)}.
 *
 * Source PNG sha256 (pinned by apps/web/lib/site/__tests__/tier-paths.test.ts,
 * so a changed PNG with a stale trace fails loudly instead of drifting):
${results.map((r) => ` * - ${r.tier}.png: ${r.sha256}`).join("\n")}
 */
export type Tier = "chopstick" | "noodle-master" | "beef-boss";

export interface TierPathDef {
  /** viewBox taken from the traced SVG's own width/height, not a fixed grid. */
  viewBox: string;
  /** Compound outline path (evenodd fill rule) traced from the source PNG. */
  d: string;
  /** sha256 of the exact PNG this path was traced from. */
  sha256: string;
}

export const TIER_PATHS: Record<Tier, TierPathDef> = {
${results
  .map(
    (r) =>
      `  "${r.tier}": { viewBox: ${JSON.stringify(r.viewBox)}, sha256: ${JSON.stringify(r.sha256)}, d: ${JSON.stringify(r.d)} },`,
  )
  .join("\n")}
};
`;

writeFileSync(outFile, fileHeader);

console.log(`wrote ${outFile}`);
for (const r of results) {
  console.log(`  ${r.tier}: viewBox=${r.viewBox} path length=${r.d.length} sha256=${r.sha256}`);
}
