#!/usr/bin/env node
/**
 * Builds the tier-mark sprite (Task G2a) from the traced paths in
 * apps/web/components/site/tiers/tier-paths.ts (scripts/trace-tier-marks.mjs
 * writes that file from the owner's art; this never re-traces anything).
 *
 * Why: <TierMark> used to inline the traced path data. The noodle-master
 * trace alone is about 21 KB, and inlining put all three marks (27 KB) into
 * the site's shared JS (the dock shows a mark) and each mark twice into the
 * HTML (markup plus the RSC payload). Now the large marks are <symbol>s in
 * one static, cacheable file that <TierMark> references with <use href>, and
 * only the small chopstick mark (the dock's) stays inline so the dock never
 * waits for a file.
 *
 *   node scripts/build-tier-sprite.mjs
 *
 * Writes apps/web/public/tiers/marks.svg and
 * apps/web/components/site/tiers/tier-sprite.ts. Re-run it after
 * trace-tier-marks.mjs; lib/site/__tests__/tier-sprite.test.ts fails until
 * you do.
 */
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const WEB = path.resolve(HERE, "../apps/web");
const INLINE = ["chopstick"];

const src = readFileSync(path.join(WEB, "components/site/tiers/tier-paths.ts"), "utf8");
const entries = [...src.matchAll(/"([a-z-]+)": \{ viewBox: "([^"]+)", sha256: "[0-9a-f]+", d: "([^"]+)" \}/g)].map((m) => ({
  tier: m[1],
  viewBox: m[2],
  d: m[3],
}));
if (entries.length !== 3) throw new Error(`expected 3 tiers in tier-paths.ts, found ${entries.length}`);

// Coordinates to 0.1 of a unit (the viewBoxes are about 1000 units across,
// so that's a ten-thousandth of the mark: invisible at any size we draw).
const compact = (d) => d.replace(/-?\d+\.\d+/g, (n) => String(Math.round(Number(n) * 10) / 10)).replace(/, /g, ",");

const sprite = `<svg xmlns="http://www.w3.org/2000/svg">${entries
  .filter((e) => !INLINE.includes(e.tier))
  .map((e) => `<symbol id="${e.tier}" viewBox="${e.viewBox}"><path d="${compact(e.d)}" fill-rule="evenodd"/></symbol>`)
  .join("")}</svg>\n`;
const version = createHash("sha256").update(sprite).digest("hex").slice(0, 10);
writeFileSync(path.join(WEB, "public/tiers/marks.svg"), sprite);

const viewBoxes = entries.map((e) => `  "${e.tier}": "${e.viewBox}",`).join("\n");
const inline = entries
  .filter((e) => INLINE.includes(e.tier))
  .map((e) => `  "${e.tier}": "${e.d}",`)
  .join("\n");
writeFileSync(
  path.join(WEB, "components/site/tiers/tier-sprite.ts"),
  `/**
 * GENERATED by scripts/build-tier-sprite.mjs (Task G2a) from tier-paths.ts.
 * Do not edit by hand. <TierMark> renders the small chopstick mark inline and
 * the others from public/tiers/marks.svg (<use href>), versioned by content.
 */
import type { Tier } from "./tier-paths";

export const TIER_SPRITE_URL = "/tiers/marks.svg?v=${version}";

export const TIER_VIEWBOX: Record<Tier, string> = {
${viewBoxes}
};

/** Marks drawn inline (no file request): the dock's. */
export const TIER_INLINE_PATHS: Partial<Record<Tier, string>> = {
${inline}
};
`,
);
console.log(`wrote marks.svg (${sprite.length} bytes, v=${version}) and tier-sprite.ts`);
